/// A Bluetooth device by the icon name BlueZ gives it.
pub fn device(icon: &str) -> Icon {
    match icon {
        "audio-headset" | "audio-headphones" | "audio-card" => HEADPHONES,
        "input-mouse" | "input-tablet" => MOUSE,
        "input-keyboard" => KEYBOARD,
        "input-gaming" => GAMEPAD,
        "audio-speakers" => SPEAKER,
        _ => BLUETOOTH,
    }
}

